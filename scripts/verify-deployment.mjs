import assert from 'node:assert/strict';
const supplied=process.argv[2];
if(!supplied)throw new Error('Usage: npm run verify:deployment -- https://your-public-domain');
const origin=new URL(supplied);
const expectedOrigin=new URL(process.argv[3]||supplied);
assert(['http:','https:'].includes(origin.protocol),'Use HTTP(S).');
assert(!origin.username&&!origin.password,'Do not put credentials in the URL.');
const check=async path=>{
 const response=await fetch(new URL(path,origin),{redirect:'follow',signal:AbortSignal.timeout(20000)});
 assert.equal(response.status,200,`${path} returned ${response.status}; check deployment protection and build logs.`);
 return {response,body:await response.text()};
};
const routes=['/','/services','/specialists','/about','/reviews','/vacancies','/contacts'];
for(const path of routes){
 const {response,body}=await check(path);
 assert(/<html[^>]*lang="ru"/.test(body),`${path}: Russian language missing.`);
 assert(body.includes('Созвездие речи'),`${path}: page content missing; a login page may have been returned.`);
 assert(/href="tel:[+0-9]+"/.test(body),`${path}: booking phone missing.`);
 const match=body.match(/<link[^>]*rel="canonical"[^>]*href="([^"]+)"/);
 assert(match,`${path}: production canonical missing.`);
 const canonical=new URL(match[1]);
 assert.equal(canonical.protocol,'https:',`${path}: production canonical must use HTTPS.`);
 assert.equal(canonical.origin,expectedOrigin.origin,`${path}: wrong canonical domain.`);
 assert.equal(canonical.pathname,path,`${path}: wrong canonical path.`);
 assert(!/<link[^>]*rel="canonical"[^>]*href="https?:\/\/(localhost|127\.0\.0\.1)/.test(body),'Loopback canonical found.');
 assert.equal(response.headers.get('x-content-type-options'),'nosniff','Security header missing.');
 console.log(`PASS ${path}`);
}
const {body:robots}=await check('/robots.txt');
assert(/Sitemap: https:\/\//.test(robots),'Production sitemap entry missing.');
assert(!/Disallow: \/\s/.test(robots+'\n'),'Production robots blocks indexing.');
const {body:sitemap}=await check('/sitemap.xml');
assert.equal((sitemap.match(/<loc>/g)||[]).length,7,'Expected seven sitemap URLs.');
for(const match of sitemap.matchAll(/<loc>([^<]+)<\/loc>/g))assert.equal(new URL(match[1]).origin,expectedOrigin.origin,'Wrong sitemap domain.');
const {body:home}=await check('/');
assert(!home.includes('fonts.googleapis.com')&&!home.includes('fonts.gstatic.com'),'External font dependency found.');
const fontLink=[...home.matchAll(/<link\b[^>]+>/g)].map(m=>m[0]).find(tag=>tag.includes('as="font"'));
assert(fontLink,'Local font preload missing.');
const fontUrl=fontLink.match(/href="([^"]+)"/)[1];
const font=await fetch(new URL(fontUrl,origin),{signal:AbortSignal.timeout(20000)});
assert.equal(font.status,200,'Local font failed to load.');
for(const path of ['/images/hero-lesson.jpg','/images/about-movement.jpg','/icon.svg'])await check(path);
const optimized=await fetch(new URL('/_next/image?url=%2Fimages%2Fhero-lesson.jpg&w=640&q=75',origin),{signal:AbortSignal.timeout(20000)});
assert.equal(optimized.status,200,'Standard Next/Image optimization failed.');
assert(optimized.headers.get('content-type')?.startsWith('image/'),'Image content type missing.');
const missing=await fetch(new URL('/nonexistent-page-check',origin),{signal:AbortSignal.timeout(20000)});
assert.equal(missing.status,404,'Missing page must return 404.');
assert((await missing.text()).includes('Страница не найдена'),'404 must be Russian.');
console.log('PASS robots, sitemap, assets, Next/Image and Russian 404.');
console.log('This verifies access from this machine only; separately test from Russian mobile and fixed-line networks.');
